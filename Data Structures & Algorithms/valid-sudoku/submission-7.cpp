class Solution { 
public: 
    bool isValidSudoku(const vector<vector<char>> &board) { 
            for (int i = 0; i < 9; ++i) {
                int fred = (i/3) * 3;

                for (int j = 0; j < 9; ++j) {
                    int sam = (j/3) * 3;

                    if (board[i][j] == '.') {
                        continue;
                    }

                    for (int rowBuddyIdx = 0; rowBuddyIdx < 9; ++rowBuddyIdx) {
                        if (board[i][j] == board[i][rowBuddyIdx] && rowBuddyIdx != j) {
                            return false;
                        }
                    }

                    for (int colBuddyIdx = 0; colBuddyIdx < 9; ++colBuddyIdx) {
                        if (board[i][j] == board[colBuddyIdx][j] && colBuddyIdx != i) {
                            return false;
                        }
                    }

                    for (int squareRowIdx = fred; squareRowIdx < fred + 3; ++squareRowIdx) {
                        for (int squareColIdx = sam; squareColIdx < sam + 3; ++squareColIdx) {
                            cout << "rowStart: " << fred << " colStart: " << sam << " board[" << i << "][" << j <<"]: " << board[i][j] << " board[" << squareRowIdx << "][" << squareColIdx << "]: " << board[squareRowIdx][squareColIdx] << endl;

                            if (board[i][j] == board[squareRowIdx][squareColIdx] && squareRowIdx != i && squareColIdx != j) {
                                return false;
                            }
                        }
                    }
                }
            }

            return true;
        } 
    };


